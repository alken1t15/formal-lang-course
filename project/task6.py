"""Weak Chomsky normal form and Hellings context-free path queries."""

from collections import defaultdict, deque

from networkx import DiGraph
from pyformlang.cfg import CFG, Production, Terminal, Variable

from project.task2 import graph_to_nfa


def cfg_to_weak_normal_form(cfg: CFG) -> CFG:
    """Return an equivalent grammar with rules A -> BC, A -> a or A -> epsilon.

    Unlike ordinary CNF conversion, epsilon productions are preserved.
    The input grammar and its productions are not modified.
    """
    grammar = cfg.eliminate_unit_productions().remove_useless_symbols()
    used_variables = set(cfg.variables)
    productions = set()
    terminal_variables = {}
    counter = 0

    def fresh_variable():
        nonlocal counter
        while True:
            variable = Variable(f"__WCNF_{counter}")
            counter += 1
            if variable not in used_variables:
                used_variables.add(variable)
                return variable

    for production in grammar.productions:
        if len(production.body) <= 1:
            productions.add(production)
            continue

        # Terminals in longer bodies need their own single-terminal productions.
        body = []
        for symbol in production.body:
            if isinstance(symbol, Terminal):
                if symbol not in terminal_variables:
                    variable = fresh_variable()
                    terminal_variables[symbol] = variable
                    productions.add(Production(variable, [symbol]))
                symbol = terminal_variables[symbol]
            body.append(symbol)

        # A -> B C D becomes A -> B X, X -> C D with a fresh X.
        head = production.head
        for index in range(len(body) - 2):
            tail = fresh_variable()
            productions.add(Production(head, [body[index], tail]))
            head = tail
        productions.add(Production(head, body[-2:]))

    return CFG(start_symbol=cfg.start_symbol, productions=productions)


def hellings_based_cfpq(
    cfg: CFG,
    graph: DiGraph,
    start_nodes: set[int] | None = None,
    final_nodes: set[int] | None = None,
) -> set[tuple[int, int]]:
    """Find graph paths whose labels are generated by the grammar.

    Omitted or empty endpoint sets select all vertices, as in previous tasks.
    A work item (A, u, v) means that A derives a path from u to v.
    """
    automaton = graph_to_nfa(graph, start_nodes, final_nodes)
    grammar = cfg_to_weak_normal_form(cfg)
    terminal_heads = defaultdict(set)
    left_rules = defaultdict(set)
    right_rules = defaultdict(set)
    epsilon_heads = set()
    for production in grammar.productions:
        head, body = production.head, production.body
        if not body:
            epsilon_heads.add(head)
        elif len(body) == 1:
            terminal_heads[body[0]].add(head)
        else:
            left, right = body
            left_rules[left].add((head, right))
            right_rules[right].add((head, left))

    known = set()
    agenda = deque()
    outgoing = defaultdict(set)
    incoming = defaultdict(set)

    def add_path(variable, source, target):
        path = (variable, source, target)
        if path not in known:
            known.add(path)
            outgoing[source, variable].add(target)
            incoming[target, variable].add(source)
            agenda.append(path)

    # Empty paths exist at every vertex, including isolated vertices.
    for state in automaton.states:
        for variable in epsilon_heads:
            add_path(variable, state.value, state.value)
    for source, transitions in automaton.to_dict().items():
        for symbol, targets in transitions.items():
            for head in terminal_heads.get(Terminal(symbol.value), ()):
                for target in targets:
                    add_path(head, source.value, target.value)

    while agenda:
        variable, source, target = agenda.popleft()
        # Append a known C-path to the current B-path for each A -> B C.
        for head, right in left_rules.get(variable, ()):
            for end in tuple(outgoing.get((target, right), ())):
                add_path(head, source, end)
        # Prepend a known B-path to the current C-path for each A -> B C.
        # Snapshots allow add_path to extend these indices during iteration.
        for head, left in right_rules.get(variable, ()):
            for begin in tuple(incoming.get((source, left), ())):
                add_path(head, begin, target)

    starts = {state.value for state in automaton.start_states}
    finals = {state.value for state in automaton.final_states}
    return {
        (source, target)
        for variable, source, target in known
        if variable == grammar.start_symbol and source in starts and target in finals
    }
